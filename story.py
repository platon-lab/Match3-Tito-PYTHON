def chapter_beats(c):
    """Катсцена главы c: глава 1 — уровень 10, глава 2 — уровень 20 и так до уровня 1000."""
    if 1 <= c <= len(HAND_CHAPTERS):
        return HAND_CHAPTERS[c - 1]
    rng = random.Random(4000 + c)
    n = c * 10
    bg = CHAPTER_BGS[c % len(CHAPTER_BGS)]
    place = CHAPTER_PLACES[c % len(CHAPTER_PLACES)]
    beats = [B("NAR", rng.choice(CH_NAR).format(n=n, place=place, smell=rng.choice(SMELLS)),
               bg=bg, title=f"ГЛАВА {c}")]
    if rng.random() < 0.7:
        beats.append(B("NAR", rng.choice(CH_TWIST).format(event=rng.choice(EVENTS)), bg=bg))
    if rng.random() < 0.3:
        text = f"{rng.choice(MUR_SAYS)} {rng.choice(MUR_END)}"
        beats.append(B("MUR", text, bg=bg, cast=["MUR"]))
    else:
        text = f"{rng.choice(TITO_SAYS)} {rng.choice(TITO_END)}"
        beats.append(B("TITO", text, bg=bg, cast=["TITO"]))
    return beats


