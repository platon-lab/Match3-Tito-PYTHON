def boss_beats(n):
    """Катсцена перед боссом на уровне n (кратном BOSS_EVERY)."""
    b = max(1, n // BOSS_EVERY)
    k = (b - 1) % len(BOSS_NAMES)
    name, color = BOSS_NAMES[k], BOSS_COLORS[k]
    talk, reply = BOSS_TALK[k]
    art_kind = k % 6            # внешний вид: 6 рисунков боссов
    return [
        B("NAR", f"Появляется босс: {name}", bg="arena", title=f"БОСС {b}", boss=art_kind,
          cast=["TITO"], shake=True, sound="roar"),
        B("BOSS", talk, bg="arena", boss=art_kind, cast=["TITO", "BOSS"], name=name, color=color,
          shake=True),
        B("TITO", reply, bg="arena", boss=art_kind, cast=["TITO", "BOSS"]),
    ]


def new_mechanics(cfg, seen):
    """Механики уровня, которые игрок ещё не видел в катсцене."""
    return [m for m in cfg["mech"] if m not in seen]


def level_beats(cfg, new):
    """Катсцена перед уровнем: новые механики, глава каждые 10 уровней, тяжёлый уровень."""
    beats = []
    for m in new:
        beats += MECH_BEATS[m]
    n = cfg["n"]
    if n % 10 == 0 and not cfg["boss"]:
        beats += chapter_beats(n // 10)
    if cfg["hard"]:
        beats += HARD_BEATS
    return beats


def cutscene_catalog(max_level=MAX_LEVEL):
    """Все катсцены игры по порядку: главы, боссы, новые механики, тяжёлый уровень. Для дебаг-меню."""
    out = []
    for c in range(1, max_level // 10 + 1):
        out.append((f"Глава {c} · уровень {c * 10}", chapter_beats(c)))
    for k in range(1, max_level // BOSS_EVERY + 1):
        n = BOSS_EVERY * k
        out.append((f"Босс {k}: {BOSS_NAMES[(k - 1) % len(BOSS_NAMES)]} · уровень {n}", boss_beats(n)))
    for m, beats in MECH_BEATS.items():
        out.append((f"Механика: {MECH_NAMES[m]}", beats))
    out.append(("Тяжёлый уровень", HARD_BEATS))
    return out


def all_voice_texts():
    """Все реплики игры, которые нужно озвучить (для make_voice.py и фоновой загрузки)."""
    out = []

    def add(t):
        if t and t not in out:
            out.append(t)

    for beats in MECH_BEATS.values():
        for b in beats:
            add(b["text"])
    for b in HARD_BEATS:
        add(b["text"])
    for ch in HAND_CHAPTERS:
        for b in ch:
            add(b["text"])
    for c in range(len(HAND_CHAPTERS) + 1, MAX_LEVEL // 10 + 1):
        for b in chapter_beats(c):
            add(b["text"])
    for k in range(1, MAX_LEVEL // BOSS_EVERY + 1):
        for b in boss_beats(BOSS_EVERY * k):
            add(b["text"])
    for h in HINTS:
        add(h)
    for t in RESULT_LINES:
        add(t)
    for _, _, t in INTRO_LINES:
        add(t)
    return out
